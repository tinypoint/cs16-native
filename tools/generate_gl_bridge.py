#!/usr/bin/env python3
"""Generate Win32 stack marshalling from local Apple SDK GL declarations.

Only scalar calls and fixed-size input vectors are generated. Other core
entries resolve to explicit failure traps until implemented by hand.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def main():
    header=Path('/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk/System/Library/Frameworks/OpenGL.framework/Headers/gl.h').read_text()
    declarations=re.findall(r'extern\s+(void|GLboolean|GLint|GLuint|GLenum)\s+(gl\w+)\s*\(([^\n]*)\) OPENGL_DEPRECATED',header)
    scalar={'GLenum','GLbitfield','GLboolean','GLbyte','GLshort','GLint','GLsizei','GLubyte','GLushort','GLuint','GLfloat','GLclampf','GLdouble','GLclampd'}
    manual={'glGetError','glGetString','glGetIntegerv','glGetFloatv','glGenTextures','glDeleteTextures','glTexImage2D','glTexSubImage2D','glReadPixels','glLoadMatrixf','glMultMatrixf','glVertexPointer','glTexCoordPointer','glColorPointer','glNormalPointer','glDrawArrays','glDrawElements'}
    code=['/* Generated by tools/generate_gl_bridge.py from SDK API signatures. */'];names=[];unsupported=[]
    for result,name,parameters in declarations:
        if name in names+unsupported or name in manual:continue
        if name=='glDrawRangeElements':continue
        if name=='glArrayElement':unsupported.append(name);continue
        params=[] if parameters.strip()=='void' else parameters.split(',')
        args=[];index=0;checks=[];valid=True
        for param in params:
            match=re.fullmatch(r'\s*(const\s+)?(GL\w+)\s*(\*?)\s*(\w+)\s*',param)
            if not match:valid=False;break
            const,typ,pointer,pname=match.groups()
            if typ not in scalar:valid=False;break
            if pointer:
                vector=re.fullmatch(r'gl(?:Vertex|Color|TexCoord|RasterPos|Normal|MultiTexCoord)([1234])(?:b|ub|s|us|i|ui|f|d)v',name)
                if not const or not vector:valid=False;break
                count=int(vector.group(1));checks.append(f'gl_buffer(A32({index}),{count}*sizeof({typ}),0);')
                args.append(f'(const {typ} *)gm_ptr(A32({index}))');index+=1
            else:
                args.append(f'({typ})'+(f'gl_double({index})' if typ in ('GLdouble','GLclampd') else f'gl_float({index})' if typ in ('GLfloat','GLclampf') else f'A32({index})'))
                index+=2 if typ in ('GLdouble','GLclampd') else 1
        if not valid:unsupported.append(name);continue
        invocation=f'{name}('+','.join(args)+')'
        finish=invocation+f';RET(0,{index});' if result=='void' else f'RET({invocation},{index});'
        code.append(f'static void bridge_{name}(void){{gl_require();'+''.join(checks)+finish+'}')
        names.append(name)
        if name=='glViewport':break
    code.append('static const win32hle_shim scalar_gl_shims[]={')
    code.extend(f'{{"{name}",bridge_{name}}},' for name in names);code.append('{0,0}};')
    code.append('static const char *unsupported_gl_entries[]={'+','.join('"'+n+'"' for n in unsupported)+'};')
    path=ROOT/'runtime/win32/opengl_bindings.inc';path.write_text('\n'.join(code)+'\n')
    print('Generated',len(names),'bindings;',len(unsupported),'explicit failure entries')
if __name__=='__main__':main()
